    function formatStopTime(value) {
      if (!/^\d{2}:\d{2}$/.test(value)) return 'Flexible';
      const [hour, minute] = value.split(':').map(Number);
      const period = hour < 12 ? 'AM' : 'PM';
      const display = `${hour % 12 || 12}:${String(minute).padStart(2, '0')} ${period}`;
      return pageLanguage === 'km'
        ? `${localizeDigits(display.replace('AM', 'ព្រឹក').replace('PM', 'ល្ងាច'))}`
        : display;
    }

    function editStopTime(button) {
      const card = button.closest('.stop-item');
      const label = card && card.querySelector('[data-stop-time]');
      if (!card || !label || label.nextElementSibling?.matches('input[type="time"]')) return;

      const input = document.createElement('input');
      input.type = 'time';
      input.value = /^\d{2}:\d{2}$/.test(card.dataset.time || '') ? card.dataset.time : '';
      input.className = 'h-8 w-[132px] rounded-md border border-[#D5DDD9] bg-white px-2 text-xs font-semibold text-on-surface focus:border-primary focus:outline-none focus:ring-1 focus:ring-primary';
      input.setAttribute('aria-label', pageLanguage === 'km' ? 'ប្ដូរម៉ោង' : `Change time for ${card.querySelector('h3')?.textContent || 'stop'}`);
      let finished = false;

      function finish(save) {
        if (finished || !input.isConnected) return;
        finished = true;
        if (save) {
          card.dataset.time = input.value;
          label.textContent = formatStopTime(input.value);
        }
        input.replaceWith(label);
        button.hidden = false;
      }

      input.addEventListener('change', () => finish(true));
      input.addEventListener('keydown', (event) => {
        if (event.key === 'Enter') finish(true);
        if (event.key === 'Escape') finish(false);
      });
      label.replaceWith(input);
      button.hidden = true;
      input.focus();
    }

